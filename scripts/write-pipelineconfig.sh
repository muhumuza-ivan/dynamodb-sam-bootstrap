#!/usr/bin/env bash
# Writes the app repo's SAM pipeline config (.aws-sam/pipeline/pipelineconfig.toml)
# from this repo's stack outputs, registering the dev and prod stages for
# `sam pipeline init`. This replaces `sam pipeline bootstrap`, which would
# otherwise create its own duplicate roles and buckets.
#
# Usage: GITHUB_ORG=<org-or-user> ./scripts/write-pipelineconfig.sh [app-repo-dir]
#        (app-repo-dir defaults to ../dynamodb-sam)
set -euo pipefail

: "${GITHUB_ORG:?Set GITHUB_ORG to the GitHub user/org that owns the app repo}"
REGION="${AWS_REGION:-eu-west-1}"
APP_NAME="${APP_NAME:-dynamodb-sam}"
APP_REPO="${APP_REPO:-dynamodb-sam}"

cd "$(dirname "$0")/.."
APP_DIR="${1:-../${APP_REPO}}"
[[ -f "${APP_DIR}/template.yaml" ]] || { echo "No SAM app at ${APP_DIR}" >&2; exit 1; }

output() {
  aws cloudformation describe-stacks --region "$REGION" --stack-name "$1" \
    --query "Stacks[0].Outputs[?OutputKey=='$2'].OutputValue" --output text
}

config="${APP_DIR}/.aws-sam/pipeline/pipelineconfig.toml"
mkdir -p "$(dirname "$config")"
{
  echo "# Generated by dynamodb-sam-bootstrap/scripts/write-pipelineconfig.sh"
  echo "# from the dynamodb-sam-pipeline-<stage> stacks. Do not edit by hand."
  echo 'version = 0.1'
  echo
  echo '[default.pipeline_bootstrap.parameters]'
  echo 'oidc_provider_url = "https://token.actions.githubusercontent.com"'
  echo 'oidc_client_id = "sts.amazonaws.com"'
  echo 'oidc_provider = "github-actions"'
  echo 'permissions_provider = "OpenID Connect (OIDC)"'
  for env in dev prod; do
    stack="${APP_NAME}-pipeline-${env}"
    echo
    echo "[${env}.pipeline_bootstrap.parameters]"
    echo "pipeline_execution_role = \"$(output "$stack" PipelineExecutionRoleArn)\""
    echo "cloudformation_execution_role = \"$(output "$stack" CloudFormationExecutionRoleArn)\""
    echo "artifacts_bucket = \"$(output "$stack" ArtifactsBucketName)\""
    echo 'image_repository = ""'
    echo "region = \"${REGION}\""
  done
} > "$config"

echo "Wrote ${config}"
echo "Next, in ${APP_DIR}: sam pipeline init  (AWS Quick Start > GitHub Actions > stages dev, prod)"
